export function getUnknownAccessibilityBaselineStoryIds(
  storyIds: readonly string[],
  baseline: readonly StorybookAccessibilityBaselineEntry[] = storybookAccessibilityBaseline,
): string[] {
  const knownStoryIds = new Set(storyIds);
  return [...new Set(baseline.map((entry) => entry.storyId))].filter((storyId) => !knownStoryIds.has(storyId));
}

export function compareStorybookAccessibilityViolations(
  storyId: string,
  violations: readonly { id: string }[],
  baseline: readonly StorybookAccessibilityBaselineEntry[] = storybookAccessibilityBaseline,
): { unexpectedRuleIds: string[]; staleRuleIds: string[] } {
  const expectedRuleIds = new Set(baseline.filter((entry) => entry.storyId === storyId).map((entry) => entry.ruleId));
  const actualRuleIds = new Set(violations.map((violation) => violation.id));
  return {
    unexpectedRuleIds: [...actualRuleIds].filter((ruleId) => !expectedRuleIds.has(ruleId)).sort(),
    staleRuleIds: [...expectedRuleIds].filter((ruleId) => !actualRuleIds.has(ruleId)).sort(),
  };
}
